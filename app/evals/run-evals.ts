// npm run evals → runs every automated test + the backtest and writes ../submission/3-evals.md
import { execFileSync } from 'node:child_process';
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { demandSeries, simulateApp, simulateToday, type PolicyResult } from './backtest';

const here = dirname(fileURLToPath(import.meta.url));
const app = resolve(here, '..');
const out = resolve(app, '../submission/3-evals.md');
const json = resolve(app, 'node_modules/.tmp/vitest-results.json');
mkdirSync(dirname(json), { recursive: true });

let failedRun = false;
try {
  execFileSync('npx', ['vitest', 'run', '--reporter=json', `--outputFile=${json}`], { cwd: app, stdio: 'ignore' });
} catch {
  failedRun = true;
}
type Assertion = { fullName: string; status: string };
const results = JSON.parse(readFileSync(json, 'utf8')) as {
  numTotalTests: number; numPassedTests: number; numFailedTests: number;
  testResults: { name: string; assertionResults: Assertion[] }[];
};

const GROUPS: Record<string, string> = {
  'src/domain/time.test.ts': 'Time and the demo clock',
  'src/domain/forecast.test.ts': 'Forecast and purchase suggestion',
  'src/domain/stock.test.ts': 'Raw stock (oldest first, expiry)',
  'src/domain/booking.test.ts': 'Booking and the 5 pm cutoff',
  'src/domain/closeDay.test.ts': 'The 5 pm close: charges, shortfall, walk-in buffer',
  'src/domain/counter.test.ts': 'Counter: coupons and walk-ins',
  'src/domain/tick.test.ts': 'Automatic transitions (reminder, close)',
  'src/domain/seed.test.ts': 'Synthetic history and forecast accuracy',
  'src/services/tick.test.ts': 'Store: races and atomic writes',
  'src/services/localRepo.test.ts': 'Local mode persistence',
  'evals/backtest.test.ts': 'Backtest: app vs today',
};

const args = { weeks: 12, seed: 7 };
const d = demandSeries(args);
const avg = (id: string) => {
  const x = d.filter((q) => q.itemId === id);
  return Math.round(x.reduce((s, q) => s + q.booked + q.walkins, 0) / x.length);
};
const cautious = simulateToday({ ...args, fixedPlates: { 'item-paneer': 40, 'item-chicken': 50 } });
const average = simulateToday({ ...args, fixedPlates: { 'item-paneer': avg('item-paneer'), 'item-chicken': avg('item-chicken') } });
const appR = simulateApp(args);
const pct = (a: number, b: number) => `${((100 * a) / b).toFixed(1)}%`;
const row = (name: string, r: PolicyResult) =>
  `| ${name} | ${r.turnedAway} (${pct(r.turnedAway, r.demandPlates)}) | ${r.cookedWastePlates} | ${r.shortfallDays} of ${r.days} | ${r.rawExpiredKg} kg | ${r.mapePct === null ? '—' : `${r.mapePct}%`} |`;

const groups = results.testResults
  .map((f) => ({ file: relative(app, f.name), tests: f.assertionResults }))
  .sort((a, b) => a.file.localeCompare(b.file));

const md = `# Evals

Generated by \`npm run evals\` on ${new Date().toISOString().slice(0, 10)}. Re-run it any time; this file is overwritten.

## 1. Automated rule tests

**${results.numPassedTests} of ${results.numTotalTests} passed**${results.numFailedTests ? `, ${results.numFailedTests} failed` : ''}${failedRun && !results.numFailedTests ? ' (runner reported an error)' : ''}.

Every business rule lives in one module of pure functions and is tested directly. UI tests drive real screens against an in-memory store.

${groups.map((g) => `### ${GROUPS[g.file] ?? g.file}\n\n${g.tests.map((t) => `- ${t.status === 'passed' ? '✅' : '❌'} ${t.fullName}`).join('\n')}`).join('\n\n')}

## 2. Backtest: the app vs today's system

${args.weeks} weeks of synthetic demand (seed ${args.seed}), replayed day by day. Both policies face exactly the same demand. The first 2 weeks are warm-up for the forecast and are excluded from every policy's numbers, leaving ${appR.days} item-days and ${appR.demandPlates} plates of demand.

- **Today (cautious):** the mess cooks a fixed 40 paneer / 50 chicken, first come first served. Everyone is a walk-in.
- **Today (perfect average):** the mess cooks the true long-run average (${avg('item-paneer')} / ${avg('item-chicken')}). It can't know this in real life; it's the best a fixed amount can do.
- **The app:** a forecast-driven purchase, pre-booking until 5 pm, cooking to bookings plus a walk-in buffer, and leftover raw stock carried over.

| Policy | Students turned away | Cooked plates wasted | Days short | Raw stock expired | Forecast error |
|---|---|---|---|---|---|
${row('Today (cautious)', cautious)}
${row('Today (perfect average)', average)}
${row('The app', appR)}

**Reading it:** a cautious mess wastes nothing because it under-cooks, and ${pct(cautious.turnedAway, cautious.demandPlates)} of demand is turned away. Cooking the average still turns away ${average.turnedAway} and wastes ${average.cookedWastePlates} plates, because demand swings day to day. The app turns away ${appR.turnedAway} and wastes ${appR.cookedWastePlates}: bookings tell the kitchen the real number at 5 pm, and over-buying only leaves storable raw stock.

**Caveats:**
- The demand is synthetic, so these numbers show the mechanism, not a prediction for any real mess.
- The backtest assumes every booked student shows up. In the app, no-shows are charged anyway, so they cost the mess nothing.
- Unsold walk-in plates are counted as waste.

### Bugs the evals caught while building

1. **Censored demand.** History first recorded *confirmed* plates. On short days that hides real demand, so the forecast never learned it, and 143 of 1,869 seeded bookings got trimmed. It now records *requested* plates.
2. **Walk-in buffer stuck at zero.** The buffer was the average of walk-ins *sold*, which the buffer itself caps, so a zero buffer stayed zero forever: 439 students turned away in the backtest. It is now max(avg sold × 1.2, 10% of confirmed) and turns away ${appR.turnedAway}.

## 3. Manual walkthrough (with the demo clock)

Tick each one on the running app and add a screenshot.

- [ ] Student books 2 plates at 4 pm → a QR coupon appears → cancel → the QR disappears and the coupon says "Cancelled, not charged".
- [ ] After 5 pm the Book and Cancel buttons are gone and the card says "Booking closed".
- [ ] The 4 pm reminder appears once in the bell, even after several refreshes.
- [ ] At 5 pm the student gets the confirmation notification, and My bill shows the charge.
- [ ] Shortfall: as mess, record only 0.3 kg on a day with no carried stock, book more than 2 plates across students, jump to 5 pm. The last booking gets "Ran short, not charged" and the mess sees a shortfall banner.
- [ ] Counter: type a code to get the green card → Mark served → type the same code again to get "Already served at …".
- [ ] Walk-ins: "+1 walk-in sold" stops at the buffer.
- [ ] Reset demo data brings back a clean state.
`;

mkdirSync(dirname(out), { recursive: true });
writeFileSync(out, md);
console.log(`Wrote ${relative(process.cwd(), out)}: ${results.numPassedTests}/${results.numTotalTests} tests passed; app turned away ${appR.turnedAway}, wasted ${appR.cookedWastePlates}.`);
if (results.numFailedTests) process.exit(1);
